/**
 * Turns owner-supplied images in assets/source/ into responsive site images.
 *   npm run images
 * For each source file (png, jpg, webp) it writes client/public/img/<name>-<width>.webp
 * at several widths plus a tiny blurred placeholder, and regenerates
 * client/src/lib/siteImages.js, which components import by name.
 * Provenance for every source image is recorded in assets/source/PROVENANCE.md.
 */
import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

import sharp from "sharp";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const sourceDir = path.join(root, "assets/source");
const outDir = path.join(root, "client/public/img");
const WIDTHS = [640, 960, 1280, 1600, 2400];

await fs.mkdir(outDir, { recursive: true });
const files = (await fs.readdir(sourceDir).catch(() => [])).filter((f) => /\.(png|jpe?g|webp)$/i.test(f));

const images = {};
for (const file of files.sort()) {
  const name = path.basename(file, path.extname(file)).toLowerCase().replace(/[^a-z0-9]+/g, "-");
  const input = sharp(path.join(sourceDir, file)).rotate();
  const { width, height } = await input.metadata();
  const widths = [...new Set(WIDTHS.filter((w) => w < width).concat(width))].sort((a, b) => a - b);
  const variants = [];
  for (const w of widths) {
    const out = `${name}-${w}.webp`;
    await input.clone().resize({ width: w }).webp({ quality: 82 }).toFile(path.join(outDir, out));
    variants.push({ width: w, url: `/img/${out}` });
  }
  const tiny = await input.clone().resize({ width: 24 }).blur(1.2).webp({ quality: 40 }).toBuffer();
  images[name] = { width, height, placeholder: `data:image/webp;base64,${tiny.toString("base64")}`, variants };
  console.log(`${file} → ${widths.length} sizes (${width}×${height})`);
}

await fs.writeFile(
  path.join(root, "client/src/lib/siteImages.js"),
  `// Generated by scripts/build-images.mjs from assets/source — do not edit by hand.\nexport const SITE_IMAGES = ${JSON.stringify(images, null, 2)};\n`,
);
console.log(`${Object.keys(images).length} image(s) written.`);
